def main() -> None:
    scores: dict[int, float] = {}
    meta: dict[int, tuple] = {}
    for um, name, jockey, win_odds, pop, runs in HORSES:
        records = [RunRecord(date=d, place=p, distance=dist, field_size=fs,
                             finish_pos=fp, jockey=jockey) for (d, p, dist, fs, fp) in runs]
        ctx = RaceContext(date=RACE_DATE, place=PLACE, distance=DISTANCE,
                          field_size=FIELD, jockey=jockey)
        scores[um] = horse_score(records, ctx)
        meta[um] = (name, jockey, win_odds, pop)

    strengths = pb.strengths_from_scores(scores, temperature=1.0)
    trio = pb.trio_probabilities(strengths)

    # --- モデルの単体評価(3着内確率) ---
    rows = []
    for um in scores:
        name, jockey, win_odds, pop = meta[um]
        rows.append((um, name, jockey, win_odds, pop,
                     pb.top3_probability(strengths, um), scores[um]))
    rows.sort(key=lambda r: r[5], reverse=True)

    print(f"=== {PLACE} ダ{DISTANCE}m {FIELD}頭  {RACE_DATE}(想定)===")
    print("※騎手/厩舎勝率データ無し・重み未学習のため、地力+間隔+叩き+距離/場適性中心\n")
    print(" モデル順 馬番 馬名             単勝(人気) 3着内確率")
    for rank, (um, name, jockey, win_odds, pop, p3, sc) in enumerate(rows, 1):
        print(f"  {rank:2d}.  {um:2d} {name:<12s} {win_odds:6.1f}({pop:2d}人) {p3:6.1%}")

    # --- 推奨買い目(三連複 上位確率順)---
    print("\n三連複 期待確率の高い組み合わせ(上位10):")
    top_trio = sorted(trio.items(), key=lambda kv: kv[1], reverse=True)[:10]
    for combo, p in top_trio:
        print(f"  {'-'.join(map(str, combo))}  {p:6.2%}")

    # --- 市場とのズレ(妙味候補)---
    print("\n市場(人気)よりモデルが高評価=妙味候補:")
    by_model = {um: i + 1 for i, (um, *_rest) in enumerate(rows)}
    gaps = []
    for um, name, jockey, win_odds, pop, p3, sc in rows:
        gaps.append((pop - by_model[um], um, name, pop, by_model[um]))
    for gap, um, name, pop, mrank in sorted(gaps, reverse=True)[:4]:
        if gap > 0:
            print(f"  {um:2d} {name:<12s} 人気{pop:2d}番 → モデル{mrank:2d}位 (差+{gap})")


if __name__ == "__main__":
    main()
