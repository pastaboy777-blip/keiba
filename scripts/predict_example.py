# 実際の着順(検証用): 1着5 / 2着7 / 3着13 / 4着14 / 5着8
ACTUAL_TOP5 = [5, 7, 13, 14, 8]


def build():
    horses = []
    for um, name, jockey, win_odds, pop, runs in HORSES:
        records = [
            RunRecord(date=d, place=p, distance=dist, field_size=fs, finish_pos=fp,
                      jockey=jockey, baba=b, corner_pos=cp, agari_rank=ar)
            for (d, p, dist, fs, fp, b, cp, ar) in runs
        ]
        horses.append((um, name, win_odds, pop, records))
    return horses


def rank_with(weights: ScoreWeights, horses):
    scores = {}
    for um, name, win_odds, pop, records in horses:
        ctx = RaceContext(date=RACE_DATE, place=PLACE, distance=DISTANCE,
                          field_size=FIELD, jockey="-", baba=BABA)
        scores[um] = horse_score(records, ctx, weights=weights)
    strengths = pb.strengths_from_scores(scores, temperature=1.0)
    order = sorted(scores, key=lambda u: scores[u], reverse=True)
    return order, strengths


def show(title, order, horses):
    name_of = {um: n for um, n, *_ in horses}
    pop_of = {um: p for um, _, _, p, _ in horses}
    print(f"\n=== {title} ===")
    print(" 順 馬番 馬名             人気  実着")
    for rank, um in enumerate(order, 1):
        actual = ACTUAL_TOP5.index(um) + 1 if um in ACTUAL_TOP5 else None
        mark = "★" if um in ACTUAL_TOP5[:3] else " "
        astr = f"{actual}着" if actual else "—"
        print(f" {mark}{rank:2d}  {um:2d} {name_of[um]:<12s} {pop_of[um]:2d}人  {astr}")


def main() -> None:
    horses = build()
    print(f"船橋 ダ{DISTANCE}m {BABA} {FIELD}頭  {RACE_DATE}")
    print("実結果トリオ: 5-7-13(1着5=9人気 / 2着7=3人気 / 3着13=8人気)")

    # (A) 既定重み(脚質・末脚・馬場・間隔すべて標準)
    order_a, _ = rank_with(ScoreWeights(), horses)
    show("A. 既定重み", order_a, horses)

    # (B) 出走間隔を強調した重み(ユーザー方針: 短間隔=詰めて走らせる馬を重視)
    w_interval = ScoreWeights(interval_fit=1.8, toughness=0.6, tatakii=1.3)
    order_b, _ = rank_with(w_interval, horses)
    show("B. 出走間隔を強調", order_b, horses)

    # 5番(連闘・中5日)の順位変化
    print(f"\n5番キャストライトオン(中5日・連闘): "
          f"A={order_a.index(5)+1}位 → B={order_b.index(5)+1}位")
    print("※結果に重みを合わせ込まず、『短間隔重視』の方針のみ反映")


if __name__ == "__main__":
    main()
