def maru(n):
    if 1 <= n <= 20:
        return chr(0x245F + n)
    if 21 <= n <= 35:
        return chr(0x3250 + (n - 20))
    if 36 <= n <= 50:
        return chr(0x32B0 + (n - 35))
    return str(n)


