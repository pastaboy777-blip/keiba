def arrange(rows, swap=(), noswap=False):
    """pos を決めて、枠と騎手で位置を直す。過去走なしは鞍の中央。

    ★ 自動の入れ替えは「pos が近い隣どうし」しか直せない。
      11/10 6Rの⑫(8枠)と①(1枠)は pos では①が前なのに、段を詰める都合で
      ⑫が先頭列の2番目、①が5段下に描かれた。**段の割り当てのほうが問題**で、
      これは隣どうしの入れ替えでは直らない。だから `--swap 6:12-1` で
      馬番を指定して入れ替えられるようにしてある。ユーザーが鞍ごとに指名する。"""
    return _arrange(rows, swap, noswap)


def _arrange(rows, swap=(), noswap=False):
    """pos を決めて、枠と騎手で近い2頭を入れ替える。過去走なしは鞍の中央に置く。"""
    ps = [r['pos'] for r in rows if r['pos'] is not None]
    mid = st.median(ps) if ps else .5
    # ★ 過去走なしは鞍の中央。ただし**全頭まったく同じ値にしない**（2026-11-15、
    #   ユーザーの指摘「5R ②④⑦⑧ 1直線にならぶのは不自然」）。
    #   馬番の昇順に等間隔で中央の前後へずらす ── **乱数を使っていないので毎回同じ図**。
    #   並びの順（馬番の昇順）は中央に重ねていたときと同じで、横だけが少し散る。
    #   `--nopast-center` で元の「全部中央」に戻る。
    npw = sorted((r for r in rows if r['pos'] is None), key=lambda r: r['ub'])
    step = (0 if (NOPAST_CENTER or len(npw) < 2) else
            min(NOPAST_STEP, NOPAST_MAX / (len(npw) - 1)))
    for k, r in enumerate(npw):
        r['pos'] = min(1., max(0., mid + (k - (len(npw) - 1) / 2) * step))
        r['nopos'] = True
    for r in rows:
        if r['pos'] is None:
            r['pos'], r['nopos'] = mid, True
    by = {r['ub']: r for r in rows}
    for u1, u2 in swap:
        if u1 in by and u2 in by:
            by[u1]['pos'], by[u2]['pos'] = by[u2]['pos'], by[u1]['pos']
    rows.sort(key=lambda r: r['pos'])
    # ★★ この入れ替えを**勝手に外すな**（2026-11-11）。
    #   9Rで裏目に出たのを理由に一度削除して、10Rの図が最初に出したものと変わり、
    #   ユーザーの指摘 ──「10R最初と違うよ！」「なんで変えるの？？」。
    #   **図はユーザーが見た形が基準。** 挙動を変えるのは指示があったときだけ。
    #   止めたいときは `--noswap`（既定は入れ替えあり）。
    # ★★ 2026-11-14、**ユーザーの指示で既定を「入れ替えなし」に変えた**（ルール44）。
    #   120鞍で測ると、この入れ替えは先頭の読みを悪くしていた ──
    #   先頭的中 46.7% → 45.8%、3番手以内 80鞍 → 75鞍、位置の誤差 0.1850 → 0.2095。
    #   **11鞍で先頭が入れ替わり、正解3・不正解4。**（ルール28 と同じ向き）
    #   復活させる口は `--swapdu`。`--noswap` は「止める」のまま残してある（既定と同じ意味）。
    #   ※ `--swap 6:12-1`（馬番を指定した段の入れ替え）は**別物**で、上でそのまま効いている。
    if SWAPDU and not noswap:
        for i in range(len(rows) - 1):
            a, b = rows[i], rows[i + 1]
            if (b['pos'] - a['pos']) <= SWAP_DP and (b['uchi'] - a['uchi']) >= SWAP_DU:
                a['pos'], b['pos'] = b['pos'], a['pos']
                rows[i], rows[i + 1] = b, a
    # ★ 2026-11-15、**順位で等間隔に並べる**（上の rankify の★★）。
    #   入れ替え（--swap / SWAPDU）を済ませて並び終わったあと、最後に間隔だけを直す。
    #   **順番は1頭も動かない。** `--pos-nama` で値そのままに戻る。
    rankify(rows)
    return rows


# ★★ 2026-11-15、**斜めの縞を消す**（ユーザーの指示 ──「いろいろ検証して」
#   「足りないところ学んで」。見本のJRAの展開図と見比べて出てきた話）。
#
#   測った事実 ── 11/16 大井の12鞍で、**連続3頭が等間隔・等段差（＝斜め一直線）**に
#   なっている箇所は 1R（16頭）5か所／7R・8R・9R・10R・12R（13-14頭）4か所ずつ、合計25か所。
#   2R〜6R・11R（7-12頭・2段）は0か所。
#
#   原因 ── `rankify()` で順位どおり等間隔にすると、14頭では間隔が **59px**。
#   重なり避けの `GAP` は **136px** なので、**順位が3つ離れた馬がはじめて同じ段に入れる**。
#   `place()` は空いている段を**若い番号から**取るので、段は 0→1→2→0→1→2… と
#   **きれいに繰り返す**。段差が +1,+1,−2 の繰り返しになり、(+1,+1) の箇所が
#   **必ず斜め一直線**になる。**13頭以上で必ず起きる。**
#
#   ★★ **3段のままでは構造上消せない。** 最初にラベルの入れ替え（0→1→2 を 1→0→2 など
#     6通り）で消そうとしたが、**どれも残った**（14頭はどの入れ替えでも4か所）。
#     理由 ── 間隔59pxに対し GAP が136pxなので、**連続する3頭はかならず別の段**に
#     入らなければならない。段が3つしかないと、並びは **period 3 の繰り返し以外に有り得ない**
#     （a,b,c と置いたら4頭目は a に戻るしかない）。3つの段差は必ず合計0になり、
#     ±1 が2つと ∓2 が1つの組になるので、**繰り返しの折り返しで ±1 が必ず隣り合う**。
#     → 段のラベルをどう振っても斜めは残る。**段を1つ増やすしかない。**
#
#   → **13頭以上（＝重なり避けで3段になる鞍）だけ、段を1つ増やして4段で組む。**
#     置き方は 0→1→3→2 の繰り返しになり、段差が +1,+2,−1,−2 と**4つで一巡**するので
#     連続する段差が等しくならない ── 斜めが**1か所も出ない**。
#   ★ 決め方は総当たりではなく**決定的な深さ優先**（空いている段のうち、
#     斜めを作らないものを「いちばん長く空いている」順に試す）。**乱数は使わない。**
#     同じカードなら何度出しても同じ図になる。
#   ★ 重なりは作らない ── 候補は `x < その段の最後のx − GAP` を満たす段だけ（place と同じ式）。
#   ★ **横（left）も馬の順番も1つも動かない。** 変えたのは「どの馬をどの段に置くか」と、
#     13頭以上の鞍の**段数が3→4になる**（＝図の高さが92px増える）ことだけ。
#   ★ 12頭以下（2段）は 0,1,0,1… ＝すでに段差が交互なので斜めは0か所。**何も変えない**
#     （`--dan-nama` を付けると 11/16 大井の12鞍すべてでHTMLがバイト単位で一致する）。
#   止める口（旧の段の割り当てに戻す）は **`--dan-nama`**。
DAN_NAMA = False
SHIMA_CAP = 20000        # 深さ優先の打ち切り（これを超えたら元の割り当てのまま）


def _nshima(xs, lns):
    """斜め3頭の数。xs は横（この向きのまま連続3頭）、lns は段。

    「x の差が等しく（±3px）かつ段差が等しくゼロでない」── 報告の測り方と同じ。"""
    return sum(1 for i in range(len(xs) - 2) if _naname(xs, lns, i + 2, lns[i + 2]))


def _naname(xs, lns, i, c):
    """i 頭目を段 c に置くと、i-2・i-1・i が斜め一直線になるか。"""
    if i < 2:
        return False
    return (abs((xs[i - 1] - xs[i - 2]) - (xs[i] - xs[i - 1])) <= 3.0
            and (c - lns[i - 1]) == (lns[i - 1] - lns[i - 2]) and c != lns[i - 1])


def _assign(xs, L):
    """横が xs（この順）の馬を L 段に割り振る。重なりも斜めも作らない並びを1つ返す。

    見つからなければ None。深さ優先で、候補は
      ① 重なり避け（`x < その段の最後のx − GAP`。place と同じ式）
      ② 斜めを作らない（直前2頭との段差が等しくならない）
    を満たす段だけ。順は「まだ使っていない段 → 長く空いている段 → 段番号」で**決定的**。"""
    n = len(xs)
    last = [None] * L
    lns = []
    cnt = [0]

    def rec():
        i = len(lns)
        if i == n:
            return True
        cnt[0] += 1
        if cnt[0] > SHIMA_CAP:
            return False
        cs = [c for c in range(L)
              if (last[c] is None or xs[i] < last[c] - GAP) and not _naname(xs, lns, i, c)]
        cs.sort(key=lambda c: (0 if last[c] is None else 1,
                               -(last[c] or 0), c))
        for c in cs:
            keep = last[c]
            last[c] = xs[i]
            lns.append(c)
            if rec():
                return True
            lns.pop()
            last[c] = keep
        return False

    return lns if rec() else None


def shima(out, nl):
    """斜めの縞を消す（上の★★）。`out` は横の順（pos の昇順）。

    返すのは (out, 段数)。段数は**そのまま**か、13頭以上の鞍で**1つだけ増える**。"""
    if DAN_NAMA or nl < 3:
        return out, nl        # 2段は 0,1,0,1… ＝すでに段差が交互。1頭も動かさない
    xs = [x for r, x, ln in out]
    # 段を増やさずに済むならそのほうがよい（ラベルの入れ替えだけ・辞書順で決定的）
    lns = [ln for r, x, ln in out]
    for p in itertools.permutations(range(nl)):
        s = [p[v] for v in lns]
        if _nshima(xs, s) == 0:
            return [(r, x, s[i]) for i, (r, x, ln) in enumerate(out)], nl
    s = _assign(xs, nl + 1)          # 3段では必ずここに来る（上の★★）
    if s is None:
        return out, nl               # 見つからなければ元のまま（縞は残るが壊さない）
    return [(r, x, s[i]) for i, (r, x, ln) in enumerate(out)], nl + 1


def place(rows):
    """重なり避けで段を作る。

    ★ 「x が近い馬の段を内度順に並べ替える」後処理を一度入れたが**失敗した**
      （2026-11-11）。同じ段に x の近い馬が同居して重なる。
      段の割り当てを内外に合わせたいなら、段そのものを内外の帯にするしかないが、
      それはユーザーに「ちがう」と言われた形。**ここは重なり避けのままにする。**
      ずれている鞍は `--swap` で馬番を指定して直す。"""
    out, lanes = [], []
    for r in sorted(rows, key=lambda r: r['pos']):
        x = PAD + (1 - r['pos']) * (WID - 2 * PAD)
        for i, last in enumerate(lanes):
            if x < last - GAP:
                lanes[i] = x
                out.append((r, x, i))
                break
        else:
            lanes.append(x)
            out.append((r, x, len(lanes) - 1))
    return shima(out, max(1, len(lanes)))


